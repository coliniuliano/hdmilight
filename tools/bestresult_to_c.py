#!/usr/bin/env python3
"""Convert HyperHDR's serialized BestResult (the C++ assignments its LUT
calibrator prints, see include/lut-calibrator/BestResult.h serialize()) into
an hl_model initializer for core/.

Usage: bestresult_to_c.py bestresult.txt > firmware/main/model_calibrated.h
"""
import re
import sys


def nums(s):
    # drop identifiers/type names (double4x4, YuvConverter::YUV_COEFS, ...) but keep
    # exponents such as 4.43e-17, whose 'e' is preceded by a digit
    s = re.sub(r"(?<![0-9.])[A-Za-z_][A-Za-z0-9_:<>]*", " ", s)
    return [float(x) for x in re.findall(r"-?\d+(?:\.\d+)?(?:e[-+]?\d+)?", s)]


def fl(v):
    """C float literal: always carries a '.' or exponent so the f suffix is legal."""
    t = f"{v:.9g}"
    if "." not in t and "e" not in t:
        t += ".0"
    return t + "f"


def main(path):
    txt = open(path).read()
    g = {}
    for m in re.finditer(r"bestResult\.([\w.]+)\s*=\s*(.+?);", txt, re.S):
        g[m.group(1)] = m.group(2).strip()

    def f3(key):
        v = nums(g[key])
        return f"hl_f3_make({fl(v[0])}, {fl(v[1])}, {fl(v[2])})"

    def cols(key, n):
        v = nums(g[key])
        step = len(v) // n
        return [v[i * step:(i + 1) * step] for i in range(n)]

    out = []
    out.append("/* Generated by tools/bestresult_to_c.py from a HyperHDR calibration. */")
    out.append("#pragma once")
    out.append('#include "hl_tonemap.h"')
    out.append("static inline void hl_model_calibrated(hl_model *m)")
    out.append("{")
    out.append("    hl_model_default(m);")
    out.append(f"    m->coef = (hl_yuv_coef_t){int(nums(g['coef'])[0])};")
    cm = cols("coefMatrix", 4)
    for i, c in enumerate(cm):
        out.append(f"    m->coefMatrix.c{i} = hl_f3_make({fl(c[0])}, {fl(c[1])}, {fl(c[2])});")
    if "coloredAspectMode" in g:
        out.append(f"    m->coloredAspectMode = {int(nums(g['coloredAspectMode'])[0])};")
    ca = nums(g["colorAspect"])
    out.append(f"    m->colorAspectFirst = hl_f3_make({fl(ca[0])}, {fl(ca[1])}, {fl(ca[2])});")
    out.append(f"    m->colorAspectSecond = hl_f3_make({fl(ca[3])}, {fl(ca[4])}, {fl(ca[5])});")
    out.append(f"    m->aspect = {f3('aspect')};")
    out.append(f"    m->bt2020Range = {int(nums(g['bt2020Range'])[0])};")
    if "altConvert" in g:
        out.append(f"    m->altConvert = {int(nums(g['altConvert'])[0])};")
    pm = cols("altPrimariesToSrgb", 3)
    for i, c in enumerate(pm):
        out.append(f"    m->altPrimariesToSrgb.c{i} = hl_f3_make({fl(c[0])}, {fl(c[1])}, {fl(c[2])});")
    gamma = g["gamma"]
    gmap = {"PQ": 0, "HLG": 1, "sRGB": 2, "BT2020 with sRGB TRC": 3, "PQ in SRGB": 4, "P010": 5}
    gv = None
    for k, v in gmap.items():
        if k in gamma:
            gv = v
    if gv is None:
        gv = int(nums(gamma)[0])
    out.append(f"    m->gamma = (hl_gamma_t){gv};")
    out.append(f"    m->gammaHLG = {fl(nums(g['gammaHLG'])[0])};")
    out.append(f"    m->nits = {fl(nums(g['nits'])[0])};")
    out.append(f"    m->lchEnabled = {'true' if nums(g['lchEnabled'])[0] else 'false'};")
    out.append(f"    m->signal.range = (hl_range_t){int(nums(g['signal.range'])[0])};")
    for k in ("yRange", "upYLimit", "downYLimit", "yShift"):
        out.append(f"    m->signal.{k} = {fl(nums(g['signal.' + k])[0])};")
    out.append(f"    m->signal.isSourceP010 = {'true' if nums(g['signal.isSourceP010'])[0] else 'false'};")
    # LCH lists: three std::list<double4>{ double4{..}, ... } blocks, order low/mid/high
    lch = re.search(r"lchPrimaries\s*=\s*LchLists\s*\{(.*)\}\s*;", txt, re.S)
    if lch:
        lists = re.findall(r"std::list<double4>\s*\{(.*?)\}", lch.group(1), re.S)
        names = ["low", "mid", "high"]
        for name, body in zip(names, lists):
            entries = re.findall(r"double4\s*\{([^}]*)\}", body)
            out.append(f"    m->lch.n_{name} = {len(entries)};")
            for i, e in enumerate(entries):
                v = nums(e)
                out.append(f"    m->lch.{name}[{i}] = (hl_f4){{{fl(v[0])}, {fl(v[1])}, {fl(v[2])}, {fl(v[3])}}};")
    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(2)
    main(sys.argv[1])
